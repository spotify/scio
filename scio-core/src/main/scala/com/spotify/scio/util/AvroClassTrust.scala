package com.spotify.scio.util

import com.spotify.scio.options.AvroOptions
import org.apache.beam.sdk.harness.JvmInitializer
import org.apache.beam.sdk.options.PipelineOptions
import org.slf4j.LoggerFactory

import java.lang.reflect.{InvocationHandler, InvocationTargetException, Method, Proxy}
import java.util.concurrent.ConcurrentHashMap

import scala.jdk.CollectionConverters._
import scala.util.{Failure, Success, Try}

/**
 * Runs [[AvroClassTrust.install]] on Beam worker JVMs, including the packages in
 * [[com.spotify.scio.options.AvroOptions.getAvroTrustedPackages]]. Registered with ServiceLoader,
 * so the Beam worker harness picks it up.
 */
class AvroClassTrustInitializer extends JvmInitializer {
  override def onStartup(): Unit = AvroClassTrust.install()
  override def beforeProcessing(options: PipelineOptions): Unit = AvroClassTrust.install(options)
}

/**
 * Avro 1.12.1+ validates every class it loads by name against `ClassSecurityValidator`, and 1.12.2
 * rejects classes outside the packages listed in `org.apache.avro.SERIALIZABLE_PACKAGES`, avro
 * generated classes included. That system property is read once and can't be passed to Dataflow
 * workers. [[install]] extends the global validator to also trust:
 *
 *   - classes annotated `@org.apache.avro.specific.AvroGenerated`, i.e. records, enums and fixed
 *     generated by the avro compiler
 *   - [[DefaultTrustedClasses]], the JDK classes avro reflect tags fields with as `java-class` or
 *     `java-key-class`, e.g. `java.math.BigDecimal` string fields and `java.util.List` arrays. Avro
 *     1.11.4 to 1.12.0 trusted their whole packages by default, `java.io` and `java.net` included,
 *     which 1.12.1 dropped. `java.io.File` and `java.net.URL` aren't trusted by default
 *   - arrays of trusted classes or primitives
 *   - classes given to [[trustClasses]], e.g. by `ReflectRecordDatumFactory` for its record class
 *     and the classes of its fields
 *   - classes in the packages given to [[trustPackages]], or with the `--avroTrustedPackages`
 *     pipeline option, e.g. reflect records such as classes with `@DefaultCoder(AvroCoder.class)`
 *
 * Other classes are still checked by the validator previously in place.
 *
 * Avro is accessed by reflection, since scio-core doesn't depend on it, and skipped on versions
 * without `ClassSecurityValidator`.
 */
object AvroClassTrust {

  private val logger = LoggerFactory.getLogger(this.getClass)

  private val AvroGenerated = "org.apache.avro.specific.AvroGenerated"

  /**
   * JDK classes avro reflect schemas name in `java-class` and `java-key-class` props, trusted on
   * top of `org.apache.avro.SERIALIZABLE_PACKAGES`.
   */
  val DefaultTrustedClasses: Set[String] = Set(
    // string fields
    "java.math.BigDecimal",
    "java.math.BigInteger",
    "java.net.URI",
    // int fields
    "java.lang.Byte",
    "java.lang.Character",
    "java.lang.Short",
    // other boxed primitives and String, e.g. array items and map keys
    "java.lang.Boolean",
    "java.lang.Double",
    "java.lang.Float",
    "java.lang.Integer",
    "java.lang.Long",
    "java.lang.String",
    // arrays
    "java.util.ArrayList",
    "java.util.Collection",
    "java.util.HashSet",
    "java.util.LinkedHashSet",
    "java.util.LinkedList",
    "java.util.List",
    "java.util.Set",
    "java.util.SortedSet",
    "java.util.TreeSet",
    // maps with non-string keys
    "java.util.HashMap",
    "java.util.LinkedHashMap",
    "java.util.Map",
    "java.util.SortedMap",
    "java.util.TreeMap"
  )

  private val trustedClasses: java.util.Set[String] = {
    val set = ConcurrentHashMap.newKeySet[String]()
    DefaultTrustedClasses.foreach(set.add)
    set
  }

  // package prefixes, ending with "."
  private val trustedPackages: java.util.Set[String] = ConcurrentHashMap.newKeySet[String]()

  /**
   * Idempotent. Called when creating a [[com.spotify.scio.ScioContext]], by scio's avro readers and
   * coders, and on Beam worker JVMs by [[AvroClassTrustInitializer]]. Call it before reading avro
   * records by other means, e.g. generated builders creating nested records.
   */
  def install(): Unit = installed

  /** [[install]], also trusting the packages in `--avroTrustedPackages`. */
  def install(options: PipelineOptions): Unit = {
    Try(options.as(classOf[AvroOptions]).getAvroTrustedPackages).toOption
      .flatMap(Option(_))
      .foreach(ps => trustPackages(ps.asScala.toSeq: _*))
    install()
  }

  /** Trust classes in `packages` and their subpackages, see [[install]]. */
  def trustPackages(packages: String*): Unit = {
    val added = packages.map(_.trim).filter(_.nonEmpty).filter(p => trustedPackages.add(p + "."))
    if (added.nonEmpty) logger.info("Avro trusted packages extended with {}", added.mkString(","))
    install()
  }

  /** Trust exactly `classes`, see [[install]]. */
  def trustClasses(classes: Class[_]*): Unit = {
    val added = classes.map(_.getName).filter(trustedClasses.add)
    if (added.nonEmpty) logger.debug("Avro trusted classes extended with {}", added.mkString(","))
    install()
  }

  private def isTrusted(cls: Class[_]): Boolean =
    if (cls.isArray) isTrusted(cls.getComponentType)
    else
      cls.isPrimitive ||
      trustedClasses.contains(cls.getName) ||
      cls.getAnnotations.exists(_.annotationType().getName == AvroGenerated) ||
      trustedPackages.asScala.exists(cls.getName.startsWith)

  private lazy val installed: Boolean =
    Try(Class.forName("org.apache.avro.util.ClassSecurityValidator")) match {
      case Failure(_) =>
        logger.debug("Avro has no ClassSecurityValidator (avro < 1.12.1), every class is trusted")
        false
      case Success(validator) =>
        Try(setGlobalPredicate(validator)) match {
          case Success(_) =>
            logger.info(
              "Avro ClassSecurityValidator extended to trust @AvroGenerated classes, " +
                "reflect field classes and scio's trusted classes and packages"
            )
            true
          case Failure(e) =>
            logger.warn(
              "Failed to extend Avro ClassSecurityValidator to trust @AvroGenerated and " +
                "reflect classes. Avro may reject them with SecurityException: Forbidden, " +
                "unless their packages " +
                "are in -Dorg.apache.avro.SERIALIZABLE_PACKAGES",
              e
            )
            false
        }
    }

  private def setGlobalPredicate(validator: Class[_]): Unit = {
    val predicate =
      Class.forName("org.apache.avro.util.ClassSecurityValidator$ClassSecurityPredicate")
    val previous = validator.getMethod("getGlobal").invoke(null)
    val handler = new InvocationHandler {
      override def invoke(proxy: Any, method: Method, args: Array[AnyRef]): AnyRef =
        method.getName match {
          case "isTrusted" if isTrusted(args(0).asInstanceOf[Class[_]]) =>
            java.lang.Boolean.TRUE
          case "hashCode" if args == null => Int.box(System.identityHashCode(proxy))
          case "equals"                   => Boolean.box(proxy.asInstanceOf[AnyRef] eq args(0))
          case "toString" if args == null => s"AvroClassTrust or $previous"
          case _                          =>
            try method.invoke(previous, args: _*)
            catch { case e: InvocationTargetException => throw e.getCause }
        }
    }
    val proxy = Proxy.newProxyInstance(predicate.getClassLoader, Array(predicate), handler)
    validator.getMethod("setGlobal", predicate).invoke(null, proxy)
    ()
  }
}
